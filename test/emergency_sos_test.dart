import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:pathsaathi/models/gps_reading.dart';
import 'package:pathsaathi/models/user_profile.dart';
import 'package:pathsaathi/services/alarm_service.dart';
import 'package:pathsaathi/services/journey_repository.dart';
import 'package:pathsaathi/services/journey_tracking_service.dart';
import 'package:pathsaathi/services/location_service.dart';
import 'package:pathsaathi/services/messaging_service.dart';

class MockEmergencyLocationService extends LocationService {
  GpsReading? currentFix;

  @override
  Future<GpsReading?> getCurrentReading() async => currentFix;
}

class MockEmergencyAlarmService extends AlarmService {
  @override
  void stopAlarm() {}
  @override
  void dismiss() {}
}

class MockSosMessagingService extends MessagingService {
  final List<String> dispatchedRecipients = [];
  final List<String> dispatchedMessages = [];
  final List<bool> dispatchedDirectModes = [];
  int dispatchCount = 0;

  @override
  Future<MessageDeliveryStatus> sendCheckInMessage({
    required String contactName,
    required String phoneNumber,
    required String stopName,
    required String customMessage,
    String? journeyName,
    bool sendDirect = false,
  }) async {
    dispatchCount++;
    dispatchedRecipients.add(phoneNumber);
    dispatchedMessages.add(customMessage);
    dispatchedDirectModes.add(sendDirect);
    return sendDirect ? MessageDeliveryStatus.sentConfirmed : MessageDeliveryStatus.composerOpened;
  }

  @override
  Future<MessageDeliveryStatus> sendWhatsAppMessage({
    required String phoneNumber,
    required String message,
  }) async {
    return MessageDeliveryStatus.whatsAppOpened;
  }

  @override
  String formatDefaultMessage({required String stopName, String? nextStopName}) =>
      'Emergency reached $stopName';

  @override
  String maskPhoneNumber(String rawPhone) => '***-***-1234';
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  group('Issue 1: Emergency SOS Delivery & Upgrade Tests', () {
    test('formatEmergencySosMessage generates professional alert with coordinates and maps URL', () {
      const profile = UserProfile(
        userName: 'Vikram',
        defaultContactName: 'Kavitha',
        defaultContactPhone: '+91 98765 43210',
      );

      final msg = profile.formatEmergencySosMessage(
        latitude: 13.0067,
        longitude: 80.2025,
        accuracyMeters: 12.0,
        nearestLandmark: 'Guindy Metro Station',
        timestamp: DateTime(2026, 11, 20, 3, 30),
      );

      expect(msg, contains('EMERGENCY ALERT — STOP Vanthachu'));
      expect(msg, contains('Vikram'));
      expect(msg, contains('Latitude: 13.0067'));
      expect(msg, contains('Longitude: 80.2025'));
      expect(msg, contains('https://maps.google.com/?q=13.0067,80.2025'));
      expect(msg, contains('Guindy Metro Station'));
      expect(msg, contains('20 Nov 2026, 3:30 AM'));
      expect(msg, contains('This alert was generated by STOP Vanthachu'));
    });

    test('triggerDirectEmergencySos dispatches message via composer when directSms is not active', () async {
      SharedPreferences.setMockInitialValues({});
      final repo = LocalJourneyRepository();
      await repo.saveUserProfile(
        const UserProfile(
          userName: 'Vikram',
          defaultContactName: 'Kavitha',
          defaultContactPhone: '+919876543210',
          enableDirectSms: false,
          directSmsConsentGiven: false,
        ),
      );

      final mockMessaging = MockSosMessagingService();
      final mockLocation = MockEmergencyLocationService()
        ..currentFix = GpsReading(
          latitude: 13.0827,
          longitude: 80.2707,
          accuracyMeters: 10.0,
          timestamp: DateTime.now(),
        );

      final service = JourneyTrackingService(
        repository: repo,
        locationService: mockLocation,
        alarmService: MockEmergencyAlarmService(),
        messagingService: mockMessaging,
      );

      final status = await service.triggerDirectEmergencySos();

      expect(status, equals(MessageDeliveryStatus.composerOpened));
      expect(mockMessaging.dispatchCount, equals(1));
      expect(mockMessaging.dispatchedDirectModes.last, isFalse);
      expect(mockMessaging.dispatchedRecipients.last, equals('+919876543210'));
      expect(mockMessaging.dispatchedMessages.last, contains('EMERGENCY ALERT — STOP Vanthachu'));
      expect(mockMessaging.dispatchedMessages.last, contains('Vikram'));

      service.dispose();
    });

    test('triggerDirectEmergencySos transmits direct SMS when directSms is active', () async {
      SharedPreferences.setMockInitialValues({});
      final repo = LocalJourneyRepository();
      await repo.saveUserProfile(
        const UserProfile(
          userName: 'Priya',
          defaultContactName: 'Ramesh',
          defaultContactPhone: '+919123456789',
          enableDirectSms: true,
          directSmsConsentGiven: true,
        ),
      );

      final mockMessaging = MockSosMessagingService();
      final mockLocation = MockEmergencyLocationService()
        ..currentFix = GpsReading(
          latitude: 13.0067,
          longitude: 80.2025,
          accuracyMeters: 8.0,
          timestamp: DateTime.now(),
        );

      final service = JourneyTrackingService(
        repository: repo,
        locationService: mockLocation,
        alarmService: MockEmergencyAlarmService(),
        messagingService: mockMessaging,
      );

      final status = await service.triggerDirectEmergencySos();

      expect(status, equals(MessageDeliveryStatus.sentConfirmed));
      expect(mockMessaging.dispatchCount, equals(1));
      expect(mockMessaging.dispatchedDirectModes.last, isTrue);
      expect(mockMessaging.dispatchedRecipients.last, equals('+919123456789'));

      service.dispose();
    });

    test('prevents duplicate dispatches when user taps SOS repeatedly in rapid succession', () async {
      SharedPreferences.setMockInitialValues({});
      final repo = LocalJourneyRepository();
      await repo.saveUserProfile(
        const UserProfile(
          userName: 'Vikram',
          defaultContactName: 'Kavitha',
          defaultContactPhone: '+919876543210',
        ),
      );

      final mockMessaging = MockSosMessagingService();
      final service = JourneyTrackingService(
        repository: repo,
        locationService: MockEmergencyLocationService(),
        alarmService: MockEmergencyAlarmService(),
        messagingService: mockMessaging,
      );

      // Fire two SOS calls simultaneously
      final future1 = service.triggerDirectEmergencySos();
      final future2 = service.triggerDirectEmergencySos();

      await Future.wait([future1, future2]);

      // Only one dispatch must have succeeded
      expect(mockMessaging.dispatchCount, equals(1));

      service.dispose();
    });

    test('sendWhatsAppMessage launches WhatsApp via messaging service successfully', () async {
      final messaging = MockSosMessagingService();
      final status = await messaging.sendWhatsAppMessage(
        phoneNumber: '+919876543210',
        message: 'EMERGENCY: Please check my location',
      );

      expect(status, equals(MessageDeliveryStatus.whatsAppOpened));
    });
  });
}
